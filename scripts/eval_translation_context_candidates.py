#!/usr/bin/env python3
"""Measure pre-generated translation-context candidates; never run inference.

This compares the current span-based English SRT with SRTs generated by
bounded neighboring-cue context experiments.  Every file is independently
paired to a human English reference using eval_translation.py's established
time-overlap pairing and corpus chrF implementation.  Consequently, a
candidate that changes cue timing reports its own pairing coverage rather
than silently being scored against an incompatible cue index.

Examples (no GPU or model files required):

    PYTHONPATH=subtitle_ai python scripts/eval_translation_context_candidates.py \
      --reference episode.en.hi.srt --baseline current-spans.en.srt \
      --candidate left-1-right-1=neighbor-1.en.srt \
      --candidate left-2-right-2=neighbor-2.en.srt --json context-score.json

`--candidate` may be repeated. Candidate names are labels only: this tool
does not prescribe a context construction method or alter production
translation defaults.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from eval_translation import chrf, chrf_stats, pair_cues  # noqa: E402


def _read_srt(path: Path):
    from srt import parse

    return parse(path)


def score_srt(output_path: Path, reference_cues) -> dict:
    """Return deterministic human-reference and pairing measurements."""
    output_cues = _read_srt(output_path)
    pairs = pair_cues(output_cues, reference_cues)
    stats = [chrf_stats(output_cues[index].text, reference) for index, reference in pairs]
    paired = {index for index, _ in pairs}
    return {
        "path": str(output_path),
        "cues": len(output_cues),
        "paired_cues": len(paired),
        "pairing_rate": round(len(paired) / len(output_cues), 4) if output_cues else 0.0,
        "pairs": len(pairs),
        "chrf": round(chrf(stats), 2) if stats else None,
    }


def compare_cues(baseline_path: Path, candidate_path: Path) -> dict:
    """Describe directly comparable cues without assuming equal segmentation."""
    baseline = _read_srt(baseline_path)
    candidate = _read_srt(candidate_path)
    same_timing = [
        (left, right)
        for left, right in zip(baseline, candidate)
        if left.start == right.start and left.end == right.end
    ]
    return {
        "same_index_timing_cues": len(same_timing),
        "text_differences_on_same_timing": sum(left.text != right.text for left, right in same_timing),
    }


def _candidate_spec(value: str) -> tuple[str, Path]:
    name, separator, raw_path = value.partition("=")
    if not separator or not name or not raw_path:
        raise argparse.ArgumentTypeError("must be NAME=PATH")
    return name, Path(raw_path)


def _delta(candidate: dict, baseline: dict) -> dict:
    return {
        "chrf": (round(candidate["chrf"] - baseline["chrf"], 2)
                 if candidate["chrf"] is not None and baseline["chrf"] is not None else None),
        "pairs": candidate["pairs"] - baseline["pairs"],
        "paired_cues": candidate["paired_cues"] - baseline["paired_cues"],
    }


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--reference", required=True, type=Path,
                        help="human English reference SRT, usually *.en.hi.srt")
    parser.add_argument("--baseline", required=True, type=Path,
                        help="current production span-based English SRT")
    parser.add_argument("--candidate", required=True, action="append", type=_candidate_spec,
                        metavar="NAME=PATH", help="generated neighboring-context candidate SRT")
    parser.add_argument("--json", type=Path, help="write the deterministic report as JSON")
    args = parser.parse_args(argv)

    paths = [args.reference, args.baseline, *(path for _, path in args.candidate)]
    missing = [str(path) for path in paths if not path.is_file()]
    if missing:
        parser.error(f"SRT file not found: {', '.join(missing)}")
    names = [name for name, _ in args.candidate]
    if len(set(names)) != len(names):
        parser.error("candidate names must be unique")

    reference = _read_srt(args.reference)
    baseline = score_srt(args.baseline, reference)
    candidates = []
    for name, path in args.candidate:
        score = score_srt(path, reference)
        score["name"] = name
        score["delta_vs_baseline"] = _delta(score, baseline)
        score["comparison_to_baseline"] = compare_cues(args.baseline, path)
        candidates.append(score)

    report = {
        "metric": ("corpus chrF (char 1-6, beta 2) and time-overlap pairing from "
                   "scripts/eval_translation.py; no translation inference"),
        "reference": {"path": str(args.reference), "cues": len(reference)},
        "baseline": baseline,
        "candidates": candidates,
    }
    print(f"Reference: {len(reference)} human cues")
    print(f"Baseline: chrF={baseline['chrf']} | {baseline['pairs']} pairs | "
          f"{baseline['paired_cues']}/{baseline['cues']} cues paired")
    for candidate in candidates:
        delta = candidate["delta_vs_baseline"]
        comparison = candidate["comparison_to_baseline"]
        chrf_delta = f"{delta['chrf']:+.2f} vs baseline" if delta["chrf"] is not None else "n/a"
        print(f"{candidate['name']}: chrF={candidate['chrf']} ({chrf_delta}) | "
              f"{candidate['pairs']} pairs ({delta['pairs']:+d}) | "
              f"{candidate['paired_cues']}/{candidate['cues']} cues paired | "
              f"{comparison['text_differences_on_same_timing']} text changes across "
              f"{comparison['same_index_timing_cues']} same-timing cues")
    if args.json:
        args.json.write_text(json.dumps(report, indent=2) + "\n", encoding="utf-8")
        print(f"Wrote {args.json}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
